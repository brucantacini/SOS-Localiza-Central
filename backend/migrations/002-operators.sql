CREATE TABLE SOS_OPERATORS (
  ID VARCHAR2(36 CHAR) PRIMARY KEY,
  USERNAME VARCHAR2(80 CHAR) NOT NULL UNIQUE,
  PASSWORD_HASH VARCHAR2(255 CHAR) NOT NULL,
  MUST_CHANGE_PASSWORD NUMBER(1) DEFAULT 1 NOT NULL CHECK (MUST_CHANGE_PASSWORD IN (0, 1)),
  IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CHECK (IS_ACTIVE IN (0, 1)),
  CREATED_AT VARCHAR2(24 CHAR) NOT NULL,
  UPDATED_AT VARCHAR2(24 CHAR) NOT NULL
);
CREATE TABLE SOS_OPERATOR_SESSIONS (
  TOKEN_HASH VARCHAR2(64 CHAR) PRIMARY KEY,
  OPERATOR_ID VARCHAR2(36 CHAR) NOT NULL REFERENCES SOS_OPERATORS(ID) ON DELETE CASCADE,
  CREATED_AT VARCHAR2(24 CHAR) NOT NULL,
  EXPIRES_AT VARCHAR2(24 CHAR) NOT NULL
);
CREATE INDEX SOS_OP_SESS_OPERATOR_IDX ON SOS_OPERATOR_SESSIONS (OPERATOR_ID);
CREATE INDEX SOS_OP_SESS_EXPIRES_IDX ON SOS_OPERATOR_SESSIONS (EXPIRES_AT);
