-- Run once in the application schema on an accessible Oracle database.
-- Oracle FreeSQL browser login alone is not a SQL*Net connection.
CREATE TABLE SOS_ALERTS (
  ID VARCHAR2(36 CHAR) PRIMARY KEY,
  REQUEST_ID VARCHAR2(36 CHAR) NOT NULL UNIQUE,
  REQUEST_HASH VARCHAR2(64 CHAR) NOT NULL,
  OCCURRENCE_TYPE VARCHAR2(80 CHAR) NOT NULL,
  CREATED_AT VARCHAR2(24 CHAR) NOT NULL,
  UPDATED_AT VARCHAR2(24 CHAR) NOT NULL,
  STATUS VARCHAR2(20 CHAR) DEFAULT 'novo' NOT NULL,
  VERSION NUMBER(10) DEFAULT 1 NOT NULL,
  LOCATION VARCHAR2(500 CHAR) NOT NULL,
  LOCATION_SOURCE VARCHAR2(40 CHAR) NOT NULL,
  LATITUDE NUMBER,
  LONGITUDE NUMBER,
  PROFILE_NAME VARCHAR2(120 CHAR) NOT NULL,
  PROFILE_CPF VARCHAR2(20 CHAR) NOT NULL,
  PROFILE_PHONE VARCHAR2(30 CHAR) NOT NULL,
  PROFILE_ADDRESS VARCHAR2(500 CHAR) NOT NULL,
  NOTES CLOB,
  CONSTRAINT SOS_ALERT_STATUS CHECK (STATUS IN ('novo', 'em_atendimento', 'resolvido')),
  CONSTRAINT SOS_ALERT_COORDS CHECK (
    (LATITUDE IS NULL AND LONGITUDE IS NULL) OR
    (LATITUDE IS NOT NULL AND LONGITUDE IS NOT NULL AND LATITUDE BETWEEN -90 AND 90 AND LONGITUDE BETWEEN -180 AND 180)
  )
);
CREATE INDEX SOS_ALERTS_CREATED_IDX ON SOS_ALERTS (CREATED_AT DESC, ID DESC);
CREATE INDEX SOS_ALERTS_STATUS_IDX ON SOS_ALERTS (STATUS);
